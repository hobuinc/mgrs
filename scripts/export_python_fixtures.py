"""Capture the Python GEOTRANS 3.10 oracle for Rust and WebAssembly tests.

Run explicitly after building Python: python -m scripts.export_python_fixtures.
These checked-in expectations are not regenerated by Rust/TypeScript tests.
"""

import importlib.util
import json
import warnings
from pathlib import Path

import mgrs
from benchmarks.performance import global_points

ROOT = Path(__file__).resolve().parents[1]
converter = mgrs.MGRS()


def cases(filename, function):
    spec = importlib.util.spec_from_file_location(
        "fixture_source",
        ROOT / filename,
    )
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    marks = getattr(module, function).pytestmark
    return next(mark.args[1] for mark in marks if mark.name == "parametrize")


def capture(call):
    with warnings.catch_warnings(record=True) as caught:
        warnings.simplefilter("always")
        try:
            value = call()
        except mgrs.core.MGRSError as error:
            names = mgrs.core.errors.values()
            matching = [name for name in names if name in str(error)]
            return {"error": " & ".join(matching)}
        return {"value": value, "warning": bool(caught)}


def main():
    if getattr(mgrs._native, "backend", None) == "rust":
        raise RuntimeError(
            "Generate C++ reference fixtures from a C++ backend checkout"
        )
    golden = cases(
        "tests/test_geotrans_forward.py", "test_forward_strings_match_upstream"
    )
    utm = cases(
        "tests/test_geotrans_forward.py",
        "test_utm_grid_boundaries_match_upstream",
    )
    points = [point for point, _ in golden]
    points += [
        (38.9072, -77.0369),
        (39.9526, -75.1652),
        (21.61643, -158.05325),
        (47.936537188631604, 39.88991841343011),
    ]
    points += [
        (lat, lon)
        for lat in (-80.00001, -80, -1e-8, 0, 48, 56, 64, 72, 84, 84.00001)
        for lon in (-180, -177, -1e-9, 0, 3, 6, 9, 12, 21, 33, 42, 180, 360)
    ]
    points += global_points(1000)
    forward = []
    inverse_codes = {"15SWC8081751205", "50TMK5045027900", "32TNK0000000000"}
    for lat, lon in points:
        expected = []
        for p in range(6):
            expected.append(converter.toMGRS(lat, lon, MGRSPrecision=p))
        inverse_codes.update(expected)
        forward.append({"point": [lat, lon], "codes": expected})
    for code in (
        "",
        "nonsense",
        "é",
        "04QEJ12garbage",
        "04QEJ12 garbage",
        "04QEJ 12 A 34",
        "04QEJ 97987 90670!",
        "04QEJ 97987 90670 00",
        "04QEJ 97987 9067",
        "04QEJ9798790670\0junk",
        "04QEJ9798790670\0",
        "04QEJ\0 97987 90670",
        "17SMB8287460719 is an Odd place",
        "Bad company, I can't deny\nBad, bad company, 'til the day I die",
        " ",
        "\t\r\n\v\f",
        "00NEA",
        "61NEA",
        "32XNA",
        "31VEG",
    ):
        inverse_codes.add(code)
    inverse = [
        {
            "code": code,
            "latlon": capture(lambda: converter.toLatLon(code)),
            "radians": capture(lambda: converter.toLatLon(code, False)),
            "utm": capture(lambda: converter.MGRSToUTM(code)),
        }
        for code in sorted(inverse_codes)
    ]
    utm_cases = []
    for east, north, codes in utm:
        utm_cases.append({"point": [15, "N", east, north], "codes": codes})
    document = {
        "source": "Python mgrs GEOTRANS 3.10 at 1b12e14",
        "seed": 20261021,
        "forward": forward,
        "utm": utm_cases,
        "inverse": inverse,
    }
    target = ROOT / "rust/tests/fixtures/geotrans310.json"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(
        json.dumps(document, ensure_ascii=True, separators=(",", ":")) + "\n"
    )
    print(
        f"Wrote {len(forward) * 6} forward and {len(inverse)} inverse cases "
        f"to {target}"
    )


if __name__ == "__main__":
    main()
